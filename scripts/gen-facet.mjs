// Bundles the facet shim and the conformance app into string modules that the host loads
// through the Worker Loader: objects/generated/{facet-shim,conformance-app}.ts
import { build } from "esbuild";
import { writeFileSync } from "node:fs";

async function bundle(entry, external) {
  const r = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: "esm",
    platform: "neutral",
    target: "es2023",
    external,
  });
  return r.outputFiles[0].text;
}

const root = new URL("..", import.meta.url).pathname;
const shim = await bundle(`${root}objects/facet-shim-src.ts`, ["cloudflare:*", "./user.js"]);
const app = await bundle(`${root}objects/conformance-app.ts`, ["cloudflare:*"]);
const header = "// Generated by scripts/gen-facet.mjs — do not edit.\n";
writeFileSync(`${root}objects/generated/facet-shim.ts`, `${header}export const FACET_SHIM = ${JSON.stringify(shim)};\n`);
writeFileSync(`${root}objects/generated/conformance-app.ts`, `${header}export const CONFORMANCE_APP = ${JSON.stringify(app)};\n`);
console.log(`facet shim ${shim.length}B, conformance app ${app.length}B`);
