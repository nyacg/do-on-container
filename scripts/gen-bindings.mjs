// Generates objects/generated/bindings.ts: which env names a pooled object sees as bindings.
// Source of truth = wrangler.jsonc `env.control` (the Worker that holds the real bindings) plus
// the pooled classes in objects/index.ts. Declare a binding there, rebuild, and pooled objects
// get `env.<NAME>` with the same API as on Cloudflare.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const stripComments = (s) => s.replace(/^\s*\/\/.*$/gm, "").replace(/,(\s*[}\]])/g, "$1");
const cfg = JSON.parse(stripComments(readFileSync(`${root}wrangler.jsonc`, "utf8")));
const control = cfg.env.control;
const INTERNAL = new Set(["POOL", "PLACEMENT", "CHECKPOINTS", "VERSION"]);
const out = {};
const add = (name, kind, value) => !INTERNAL.has(name) && (out[name] = value === undefined ? { kind } : { kind, value });

for (const kv of control.kv_namespaces ?? []) add(kv.binding, "kv");
for (const r2 of control.r2_buckets ?? []) add(r2.binding, "r2");
if (control.ai) add(control.ai.binding, "ai");
for (const s of control.services ?? []) add(s.binding, "service");
for (const d of control.durable_objects?.bindings ?? []) add(d.name, "do");
for (const [k, v] of Object.entries(control.vars ?? {})) if (!k.startsWith("POOL_")) add(k, "var", String(v));
// Pooled classes: `env.CONF.getByName(x)` from a pooled object reaches the pooled object
// (via Placement), wherever it lives, just as a real DO binding would.
const index = readFileSync(`${root}objects/index.ts`, "utf8");
for (const [, slug, binding] of index.matchAll(/^\s*(\w+): \{ binding: "(\w+)"/gm)) {
  if (slug === "sapp") continue; // same binding as `app`
  add(binding, `pool:${slug}`);
}
writeFileSync(
  `${root}objects/generated/bindings.ts`,
  `// Generated by scripts/gen-bindings.mjs from wrangler.jsonc — do not edit.\nimport type { BindingManifest } from "../remote-bindings";\n\nexport const BINDINGS: BindingManifest = ${JSON.stringify(out, null, 2)};\n`,
);
console.log("bindings:", Object.entries(out).map(([k, v]) => `${k}=${v.kind}`).join(" "));
